def test_new_human_markdown_requires_registration(tmp_path: Path) -> None:
    registry_path, _ = _prepare(tmp_path)
    new_path = tmp_path / "docs/new.md"
    _write(new_path, "# new\n")
    _git_add_all(tmp_path)

    with pytest.raises(sync.RegistryError, match="registration-required Markdown"):
        sync.build_projections(tmp_path, registry_path, tmp_path / sync.DEFAULT_BASELINE)


def test_changed_grandfathered_markdown_requires_registration(tmp_path: Path) -> None:
    old = "# old\n"
    registry_path, _ = _prepare(tmp_path, extra_baseline={"docs/old.md": _blob(old)})
    _write(tmp_path / "docs/old.md", old)
    _git_add_all(tmp_path)
    _write(tmp_path / "docs/old.md", "# changed\n")

    with pytest.raises(sync.RegistryError, match="docs/old.md"):
        sync.build_projections(tmp_path, registry_path, tmp_path / sync.DEFAULT_BASELINE)


def test_unchanged_grandfathered_markdown_may_remain_unregistered(tmp_path: Path) -> None:
    old = "# old\n"
    registry_path, _ = _prepare(tmp_path, extra_baseline={"docs/old.md": _blob(old)})
    _write(tmp_path / "docs/old.md", old)
    _git_add_all(tmp_path)

    _, _, outputs, missing = sync.build_projections(
        tmp_path, registry_path, tmp_path / sync.DEFAULT_BASELINE
    )
    assert missing == []
    inventory = json.loads(outputs[sync.DEFAULT_INVENTORY.as_posix()])
    row = next(item for item in inventory["entries"] if item["path"] == "docs/old.md")
    assert row["registration_state"] == "grandfathered"


