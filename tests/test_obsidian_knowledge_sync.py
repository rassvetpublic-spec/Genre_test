def test_source_fingerprint_changes_with_registered_document_blob(tmp_path: Path) -> None:
    registry_path, _ = _prepare(tmp_path)
    boundary_path = tmp_path / sync.DEFAULT_BASELINE
    _, _, outputs_before, _ = sync.build_projections(tmp_path, registry_path, boundary_path)
    before = json.loads(outputs_before[sync.DEFAULT_INVENTORY.as_posix()])["source_fingerprint"]

    _write(tmp_path / "docs/doc.md", "# changed registered document\n")
    _, _, outputs_after, _ = sync.build_projections(tmp_path, registry_path, boundary_path)
    after = json.loads(outputs_after[sync.DEFAULT_INVENTORY.as_posix()])["source_fingerprint"]
    assert after != before


