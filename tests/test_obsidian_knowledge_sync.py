def _write(path: Path, text: str = "# fixture\n") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _blob(text: str) -> str:
    data = text.encode("utf-8")
    header = f"blob {len(data)}\0".encode("ascii")
    return hashlib.sha1(header + data, usedforsecurity=False).hexdigest()


def _entry(path: str = "docs/doc.md") -> dict[str, object]:
    return {
        "path": path,
        "title": "Документ",
        "doc_type": "guide",
        "area": "project",
        "status": "active",
        "summary": "Проверочный документ.",
        "tags": ["область/project", "тип/guide", "статус/active"],
    }


def _registry(entries: list[dict[str, object]] | None = None) -> dict[str, object]:
    return {
        "schema": sync.SCHEMA,
        "schema_version": 1,
        "authority_scope": sync.AUTHORITY_SCOPE,
        "generation_direction": sync.GENERATION_DIRECTION,
        "entries": entries or [_entry()],
    }


def _baseline(blobs: dict[str, str] | None = None) -> dict[str, object]:
    return {
        "schema": sync.BASELINE_SCHEMA,
        "schema_version": 1,
        "baseline_commit": sync.BASELINE_COMMIT,
        "scope": ["AGENTS.md", "README.md", "README_RUS.md", "ROADMAP.md", "docs/**/*.md"],
        "exempt_prefixes": ["docs/development/research_radar/", "docs/research/obsidian/"],
        "exempt_paths": [sync.GENERATED_INDEX_PATH],
        "baseline_blobs": blobs or {},
    }


def _git_add_all(tmp_path: Path) -> None:
    if not (tmp_path / ".git").exists():
        subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    subprocess.run(["git", "add", "-A"], cwd=tmp_path, check=True)


def _prepare(
    tmp_path: Path,
    data: dict[str, object] | None = None,
    *,
    extra_baseline: dict[str, str] | None = None,
) -> tuple[Path, Path]:
    registry_data = data or _registry()
    baseline_blobs: dict[str, str] = dict(extra_baseline or {})
    for raw_entry in registry_data["entries"]:  # type: ignore[index]
        entry = raw_entry
        path = str(entry["path"])
        if ".." not in Path(path).parts and not path.startswith("/"):
            text = "# fixture\n"
            _write(tmp_path / path, text)
            if path.endswith(".md"):
                baseline_blobs.setdefault(path, _blob(text))
        for relation in sync.RELATION_KEYS:
            for target in entry.get(relation, []):  # type: ignore[union-attr]
                _write(tmp_path / str(target))

    registry_path = tmp_path / sync.DEFAULT_REGISTRY
    registry_path.parent.mkdir(parents=True, exist_ok=True)
    registry_path.write_text(
        json.dumps(registry_data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    boundary_path = tmp_path / sync.DEFAULT_BASELINE
    boundary_path.write_text(
        json.dumps(_baseline(baseline_blobs), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    _git_add_all(tmp_path)
    return registry_path, tmp_path / sync.DEFAULT_OUTPUT


def test_write_then_check_roundtrip_materializes_all_views(tmp_path: Path) -> None:
    _, output_path = _prepare(tmp_path)

    assert sync.main(["--repo-root", str(tmp_path), "--write"]) == 0
    assert output_path.is_file()
    assert sync.main(["--repo-root", str(tmp_path), "--check"]) == 0

    expected = [
        sync.DEFAULT_OUTPUT,
        sync.DEFAULT_INVENTORY,
        sync.DEFAULT_HOME,
        sync.DEFAULT_ANALYTICS,
        sync.DEFAULT_KNOWLEDGE_BASE,
        sync.DEFAULT_RELATIONS_BASE,
        sync.DEFAULT_TERMS_BASE,
    ]
    for path in expected:
        assert (tmp_path / path).is_file(), path

    assert "GENERATED BY tools/obsidian_knowledge_sync.py" in output_path.read_text(encoding="utf-8")
    inventory = json.loads((tmp_path / sync.DEFAULT_INVENTORY).read_text(encoding="utf-8"))
    assert inventory["authority_scope"] == sync.INVENTORY_AUTHORITY
    assert inventory["source_fingerprint"]
    base_text = (tmp_path / sync.DEFAULT_KNOWLEDGE_BASE).read_text(encoding="utf-8")
    assert "filters:" in base_text
    assert "views:" in base_text
    assert "groupBy:" in base_text


def test_build_is_deterministic(tmp_path: Path) -> None:
    registry_path, _ = _prepare(tmp_path)
    boundary_path = tmp_path / sync.DEFAULT_BASELINE
    blobs = sync.tracked_worktree_blobs(tmp_path)
    _, entries_a, outputs_a, missing_a = sync.build_projections(
        tmp_path, registry_path, boundary_path, tracked_blobs=blobs
    )
    _, entries_b, outputs_b, missing_b = sync.build_projections(
        tmp_path, registry_path, boundary_path, tracked_blobs=blobs
    )
    assert entries_a == entries_b
    assert outputs_a == outputs_b
    assert missing_a == missing_b == []


